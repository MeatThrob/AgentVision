"""
AgentVision project installer.

When AgentVision bridges to a program for the first time, it doesn't just
*read* the project — it INSTALLS the full diagnostic infrastructure into
that project. This module is the single source of truth for what gets
created and where.

Contract: given a project_root, produce a project that is fully diagnosable
by AgentVision. Anything missing gets created with sane defaults; anything
already present is left alone.

What gets installed
───────────────────
  <project>/.agentvision/                  ← AgentVision-owned dir, never
                                              touched by the bridged program
    attached.json                          ← marker + metadata (when, name, av_root)
    state.json                             ← live program state (HP/MP/run_id…)
    schema.json                            ← schema for the project's events
    README.md                              ← what these files are
  <project>/log/                           ← project's own log dir (if missing)
    log.txt                                ← text log
    actions.jsonl                          ← structured event stream
    stats/                                 ← stats sub-dir
    crashes/                               ← crash dumps
  <project>/config/                        ← config dir (if missing)
  <project>/test/                          ← test dir (if missing)
  <project>/sitecustomize.py               ← Python auto-instrumentation
                                              (only if .py files exist + no
                                               existing sitecustomize.py)

Idempotent: safe to call multiple times. Returns a report of what was
created vs already-existed so the GUI can show the user.
"""

